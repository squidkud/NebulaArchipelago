#!/usr/bin/env python3
"""Writes native/petari/src/Game/System/NebulaArchipelagoStars.inc from the APWorld's StarData.py.

Run it from anywhere after changing apworld/super_mario_galaxy_pc_port/StarData.py:
    python tools/gen_archipelago_stars.py
The game scans these tables (NebulaArchipelago.cpp): a star's location number is its position in the star table + 1.
"""
import importlib.util
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("stardata", root / "apworld/super_mario_galaxy_pc_port/StarData.py")
data = importlib.util.module_from_spec(spec)
spec.loader.exec_module(data)

# The transformation stars' requirements (Forms.py), as bit masks of the forms: each group is "one of these forms".
import sys
import types

_base = types.ModuleType("BaseClasses")


class _Any(type):
    def __getattr__(cls, name):
        return 0


_base.Item = object
_base.ItemClassification = _Any("ItemClassification", (), {})
sys.modules.setdefault("BaseClasses", _base)
_package = types.ModuleType("smgpkg")
_package.__path__ = [str(root / "apworld/super_mario_galaxy_pc_port")]
sys.modules["smgpkg"] = _package
_items = importlib.import_module("smgpkg.Items")
_forms = importlib.import_module("smgpkg.Forms")
FORM_BITS = {_items.BEE_MUSHROOM: 1, _items.BOO_MUSHROOM: 2, _items.SPRING_MUSHROOM: 4, _items.FIRE_FLOWER: 8,
             _items.ICE_FLOWER: 16, _items.FLYING_STAR: 32}


def form_masks(star_name):
    groups = [sum(FORM_BITS[item] for item in group) for group in _forms.form_requirement(star_name)]
    assert len(groups) <= 2, star_name
    return (groups + [0, 0])[:2]


lines = [
    "// Generated by tools/gen_archipelago_stars.py from apworld/super_mario_galaxy_pc_port/StarData.py: do not edit.",
    "",
    "// The galaxies, in StarData.GALAXIES' order: game name, dome (0: outside the domes), most stars asked at most.",
    "static const ApGalaxy cApGalaxies[] = {",
]
for stage, _name, dome, cap in data.GALAXIES:
    lines.append(f'    {{"{stage}", {dome}, {cap}}},')
lines += [
    "};",
    "",
    "// The stars, in StarData.STARS' order (location number = index + 1): galaxy name, scenario (1-based), kind, and the",
    "// forms the star asks for with the transformation items (two groups; each a bit mask of the forms of which one is needed:",
    "// 1 Bee, 2 Boo, 4 Spring, 8 Fire, 16 Ice, 32 Flying; 0 no group).",
    "static const ApStar cApStars[] = {",
]
for stage, scenario, name, kind in data.STARS:
    a, b = form_masks(name)
    lines.append(f'    {{"{stage}", {scenario}, ApKind_{kind}, {a}, {b}}},')
lines.append("};")
out = root / "native/petari/src/Game/System/NebulaArchipelagoStars.inc"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{out.relative_to(root)}: {len(data.GALAXIES)} galaxies, {len(data.STARS)} stars")
