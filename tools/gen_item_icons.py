#!/usr/bin/env python3
"""Builds native/petari/src/Game/System/NebulaItemIcons.inc from the pictures of tools/item_icons: the icons of the items the
Archipelago pop-up shows (NebulaAchievementToast), each a BTI file (RGBA8, 96 x 96, header and image big-endian as the game's own
textures are). An item without a picture here keeps the Archipelago logo. Run it again after changing a picture."""
import struct
from pathlib import Path

from PIL import Image

SIZE = 96
# The item number (kItem* in runtime/include/galaxy/archipelago.h) and its picture.
ITEMS = [
    (1, "oneup_mushroom"),
    (2, "star_bits"),
    (3, "power_star"),
    (4, "green_star"),
    (5, "grand_star"),
    (6, "fire_trap"),
    (7, "shock_trap"),
    (8, "freeze_trap"),
    (9, "spike_trap"),
    (10, "star_bit_thief"),
    (11, "quake_trap"),
    (12, "confusion_trap"),
    (13, "rainbow_star"),
    (14, "bee_mushroom"),
    (15, "boo_mushroom"),
    (16, "spring_mushroom"),
    (17, "fire_flower"),
    (18, "ice_flower"),
    (19, "flying_star"),
]
root = Path(__file__).resolve().parent
target = root.parent / "native/petari/src/Game/System/NebulaItemIcons.inc"


def to_bti(source):
    image = Image.open(source).convert("RGBA")
    image = image.crop(image.getchannel("A").point(lambda a: 255 if a > 8 else 0).getbbox())
    side = max(image.size)
    square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    square.paste(image, ((side - image.width) // 2, (side - image.height) // 2))
    pixels = square.load()
    for y in range(side):  # premultiplied, so the resized edge does not go dark
        for x in range(side):
            r, g, b, a = pixels[x, y]
            pixels[x, y] = (r * a // 255, g * a // 255, b * a // 255, a)
    inner = SIZE - 8
    small = square.resize((inner, inner), Image.LANCZOS)
    padded = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    padded.paste(small, (4, 4))
    pixels = padded.load()
    data = bytearray()
    for ty in range(0, SIZE, 4):
        for tx in range(0, SIZE, 4):
            ar, gb = bytearray(), bytearray()
            for y in range(4):
                for x in range(4):
                    r, g, b, a = pixels[tx + x, ty + y]
                    if a:
                        r, g, b = min(255, r * 255 // a), min(255, g * 255 // a), min(255, b * 255 // a)
                    ar += bytes((a, r))
                    gb += bytes((g, b))
            data += ar + gb
    header = (bytes((6, 1)) + struct.pack(">HH", SIZE, SIZE) + bytes((0, 0, 0, 0)) + struct.pack(">HI", 0, 0) +
              bytes((0, 0, 0, 0, 1, 1, 0, 0, 1, 0)) + struct.pack(">hI", 0, 0x20))
    assert len(header) == 0x20
    return header + bytes(data)


lines = ["// Generated by tools/gen_item_icons.py from tools/item_icons: do not edit.",
         "// BTI files (header and image big-endian): RGBA8, %d x %d." % (SIZE, SIZE)]
for number, name in ITEMS:
    blob = to_bti(root / "item_icons" / (name + ".png"))
    lines.append("alignas(32) static unsigned char cItemIcon%dBti[%d] = {" % (number, len(blob)))
    for i in range(0, len(blob), 24):
        lines.append("    " + ", ".join("0x%02X" % b for b in blob[i:i + 24]) + ",")
    lines.append("};")
lines.append("// The item numbers that have an icon, and their pictures.")
lines.append("static const int cItemIconNum = %d;" % len(ITEMS))
lines.append("static const int cItemIconNumbers[%d] = {%s};" % (len(ITEMS), ", ".join(str(n) for n, _ in ITEMS)))
lines.append("static unsigned char* const cItemIconBtis[%d] = {%s};" % (len(ITEMS), ", ".join("cItemIcon%dBti" % n for n, _ in ITEMS)))
target.write_text("\n".join(lines) + "\n")
print("wrote", target, target.stat().st_size, "bytes")
