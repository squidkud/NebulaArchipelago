#!/usr/bin/env python3
"""Builds native/petari/src/Game/System/NebulaArchipelagoLogo.inc from tools/archipelago_logo.png: the Archipelago logo as
a BTI file (RGBA8, 128 x 128, the header and the image big-endian as the game's own textures are), which the pop-up
(NebulaAchievementToast) shows in place of the Power Star. Run it again to change the picture."""
import struct
import sys
from pathlib import Path

from PIL import Image

SIZE = 128
root = Path(__file__).resolve().parent
source = Path(sys.argv[1]) if len(sys.argv) > 1 else root / "archipelago_logo.png"
target = root.parent / "native/petari/src/Game/System/NebulaArchipelagoLogo.inc"

image = Image.open(source).convert("RGBA")
image = image.crop(image.getchannel("A").getbbox())
side = max(image.size)
square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
square.paste(image, ((side - image.width) // 2, (side - image.height) // 2))

# Resize with premultiplied colours so the edge does not go dark.
pixels = square.load()
for y in range(side):
    for x in range(side):
        r, g, b, a = pixels[x, y]
        pixels[x, y] = (r * a // 255, g * a // 255, b * a // 255, a)
small = square.resize((SIZE - 8, SIZE - 8), Image.LANCZOS)
padded = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
padded.paste(small, (4, 4))
data = bytearray()
pixels = padded.load()
for ty in range(0, SIZE, 4):
    for tx in range(0, SIZE, 4):
        ar, gb = bytearray(), bytearray()
        for y in range(4):
            for x in range(4):
                r, g, b, a = pixels[tx + x, ty + y]
                if a:
                    r, g, b = min(255, r * 255 // a), min(255, g * 255 // a), min(255, b * 255 // a)
                ar += bytes((a, r))
                gb += bytes((g, b))
        data += ar + gb
header = (bytes((6, 1)) + struct.pack(">HH", SIZE, SIZE) + bytes((0, 0, 0, 0)) + struct.pack(">HI", 0, 0) +
          bytes((0, 0, 0, 0, 1, 1, 0, 0, 1, 0)) + struct.pack(">hI", 0, 0x20))
assert len(header) == 0x20
blob = header + bytes(data)
lines = [
    "// Generated by tools/gen_archipelago_logo.py from tools/archipelago_logo.png: do not edit.",
    "// A BTI file (header and image big-endian): RGBA8, %d x %d." % (SIZE, SIZE),
    "alignas(32) static unsigned char cArchipelagoLogoBti[%d] = {" % len(blob),
]
for i in range(0, len(blob), 24):
    lines.append("    " + ", ".join("0x%02X" % b for b in blob[i:i + 24]) + ",")
lines.append("};")
target.write_text("\n".join(lines) + "\n")
print("wrote", target, len(blob), "bytes")
