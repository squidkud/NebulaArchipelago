#!/usr/bin/env python3
"""Builds native/petari/src/Game/Screen/NebulaTitleLogo.inc from tools/title_logo.png: the Nebula Archipelago logo of the title
screen as a BTI file (RGBA8, 1024 x 396, header and image big-endian as the game's own textures are), which
NebulaTitleScreen puts in place of the game's logo. Run it again to change the picture:  python tools/gen_title_logo.py [image.png]"""
import struct
import sys
from pathlib import Path

from PIL import Image

WIDTH, HEIGHT = 1024, 396  # a multiple of 4 each (RGBA8 is stored in 4 x 4 tiles); the picture keeps its proportions
root = Path(__file__).resolve().parent
source = Path(sys.argv[1]) if len(sys.argv) > 1 else root / "title_logo.png"
target = root.parent / "native/petari/src/Game/Screen/NebulaTitleLogo.inc"

image = Image.open(source).convert("RGBA")
# The almost invisible haze around the letters (alpha 1 to 40 of 255, a noise of faint white specks) is cleared, and the body
# (alpha 241 and over: 253 in the picture) made fully opaque.
channel = image.getchannel("A").point([0 if a <= 40 else 255 if a >= 241 else a for a in range(256)])
image.putalpha(channel)
image = image.crop(channel.getbbox())

# Fit inside the texture with a small margin, resizing with premultiplied colours so the edge does not go dark.
margin = 4
scale = min((WIDTH - 2 * margin) / image.width, (HEIGHT - 2 * margin) / image.height)
size = (max(1, round(image.width * scale)), max(1, round(image.height * scale)))
pixels = image.load()
for y in range(image.height):
    for x in range(image.width):
        r, g, b, a = pixels[x, y]
        pixels[x, y] = (r * a // 255, g * a // 255, b * a // 255, a)
small = image.resize(size, Image.LANCZOS)
padded = Image.new("RGBA", (WIDTH, HEIGHT), (0, 0, 0, 0))
padded.paste(small, ((WIDTH - size[0]) // 2, (HEIGHT - size[1]) // 2))

data = bytearray()
pixels = padded.load()
for ty in range(0, HEIGHT, 4):
    for tx in range(0, WIDTH, 4):
        ar, gb = bytearray(), bytearray()
        for y in range(4):
            for x in range(4):
                r, g, b, a = pixels[tx + x, ty + y]
                if a:
                    r, g, b = min(255, r * 255 // a), min(255, g * 255 // a), min(255, b * 255 // a)
                ar += bytes((a, r))
                gb += bytes((g, b))
        data += ar + gb
header = (bytes((6, 1)) + struct.pack(">HH", WIDTH, HEIGHT) + bytes((0, 0, 0, 0)) + struct.pack(">HI", 0, 0) +
          bytes((0, 0, 0, 0, 1, 1, 0, 0, 1, 0)) + struct.pack(">hI", 0, 0x20))
assert len(header) == 0x20
blob = header + bytes(data)
lines = [
    "// Generated by tools/gen_title_logo.py from tools/title_logo.png: do not edit.",
    "// A BTI file (header and image big-endian): RGBA8, %d x %d." % (WIDTH, HEIGHT),
    "alignas(32) static unsigned char cTitleLogoBti[%d] = {" % len(blob),
]
for i in range(0, len(blob), 40):
    lines.append(",".join(str(b) for b in blob[i:i + 40]) + ",")
lines.append("};")
target.write_text("\n".join(lines) + "\n")
print("wrote", target, len(blob), "bytes, file", target.stat().st_size)


# ---- The glow ("bloom") behind the logo: the title layout's two bloom pictures (PicBloomA, PicBloomB) flash around the logo when
# A is pressed. Their picture is a soft, blurred copy of the logo: NebulaTitleBloom.inc (RGBA8, 512 x 240 = the logo's rectangle,
# 500 x 193 on the screen, with 40 on each side for the blur; NebulaTitleScreen sizes the pictures 580 x 273).
from PIL import ImageFilter

BW, BH = 512, 240
scale = BW / 580.0
logo_w = round(500 * scale)
logo_h = round(logo_w * HEIGHT / WIDTH)
mask = image.getchannel("A").resize((logo_w, logo_h), Image.LANCZOS)
canvas = Image.new("L", (BW, BH), 0)
canvas.paste(mask, ((BW - logo_w) // 2, (BH - logo_h) // 2))
glow = canvas.filter(ImageFilter.GaussianBlur(11)).point(lambda a: min(255, int(a * 1.15)))
bloom = Image.new("RGBA", (BW, BH), (255, 250, 235, 0))
bloom.putalpha(glow)
bdata = bytearray()
bpix = bloom.load()
for ty in range(0, BH, 4):
    for tx in range(0, BW, 4):
        ar, gb = bytearray(), bytearray()
        for y in range(4):
            for x in range(4):
                r, g, b, a = bpix[tx + x, ty + y]
                ar += bytes((a, r))
                gb += bytes((g, b))
        bdata += ar + gb
bheader = (bytes((6, 1)) + struct.pack(">HH", BW, BH) + bytes((0, 0, 0, 0)) + struct.pack(">HI", 0, 0) +
           bytes((0, 0, 0, 0, 1, 1, 0, 0, 1, 0)) + struct.pack(">hI", 0, 0x20))
bblob = bheader + bytes(bdata)
btarget = target.with_name("NebulaTitleBloom.inc")
lines = [
    "// Generated by tools/gen_title_logo.py from tools/title_logo.png: do not edit.",
    "// A BTI file (header and image big-endian): RGBA8, %d x %d." % (BW, BH),
    "alignas(32) static unsigned char cTitleBloomBti[%d] = {" % len(bblob),
]
for i in range(0, len(bblob), 40):
    lines.append(",".join(str(b) for b in bblob[i:i + 40]) + ",")
lines.append("};")
btarget.write_text("\n".join(lines) + "\n")
print("wrote", btarget, len(bblob), "bytes, file", btarget.stat().st_size)


# ---- The credits at the bottom of the title screen, in place of "(c) 2007 Nintendo" (the layout's picture PicNintendo):
# NebulaTitleCredits.inc from tools/title_credits.png (RGBA8, 640 x 184, shown 236 x 68 on the screen).
CW, CH = 640, 184
credits = Image.open(root / "title_credits.png").convert("RGBA")
calpha = credits.getchannel("A").point([0 if a <= 8 else a for a in range(256)])
credits.putalpha(calpha)
credits = credits.crop(calpha.getbbox())
cscale = min((CW - 8) / credits.width, (CH - 8) / credits.height)
csize = (max(1, round(credits.width * cscale)), max(1, round(credits.height * cscale)))
cpix = credits.load()
for y in range(credits.height):
    for x in range(credits.width):
        r, g, b, a = cpix[x, y]
        cpix[x, y] = (r * a // 255, g * a // 255, b * a // 255, a)
csmall = credits.resize(csize, Image.LANCZOS)
cpadded = Image.new("RGBA", (CW, CH), (0, 0, 0, 0))
cpadded.paste(csmall, ((CW - csize[0]) // 2, (CH - csize[1]) // 2))
cdata = bytearray()
cpix = cpadded.load()
for ty in range(0, CH, 4):
    for tx in range(0, CW, 4):
        ar, gb = bytearray(), bytearray()
        for y in range(4):
            for x in range(4):
                r, g, b, a = cpix[tx + x, ty + y]
                if a:
                    r, g, b = min(255, r * 255 // a), min(255, g * 255 // a), min(255, b * 255 // a)
                ar += bytes((a, r))
                gb += bytes((g, b))
        cdata += ar + gb
cheader = (bytes((6, 1)) + struct.pack(">HH", CW, CH) + bytes((0, 0, 0, 0)) + struct.pack(">HI", 0, 0) +
           bytes((0, 0, 0, 0, 1, 1, 0, 0, 1, 0)) + struct.pack(">hI", 0, 0x20))
cblob = cheader + bytes(cdata)
ctarget = target.with_name("NebulaTitleCredits.inc")
lines = [
    "// Generated by tools/gen_title_logo.py from tools/title_credits.png: do not edit.",
    "// A BTI file (header and image big-endian): RGBA8, %d x %d." % (CW, CH),
    "alignas(32) static unsigned char cTitleCreditsBti[%d] = {" % len(cblob),
]
for i in range(0, len(cblob), 40):
    lines.append(",".join(str(b) for b in cblob[i:i + 40]) + ",")
lines.append("};")
ctarget.write_text("\n".join(lines) + "\n")
print("wrote", ctarget, len(cblob), "bytes, file", ctarget.stat().st_size)
