#!/usr/bin/env python3
"""Builds native/petari/src/Game/Screen/NebulaTitleLogo.inc from tools/title_logo.png: the Nebula Archipelago logo of the title
screen as a BTI file (RGBA8, 1024 x 396, header and image big-endian as the game's own textures are), which
NebulaTitleScreen puts in place of the game's logo. Run it again to change the picture:  python tools/gen_title_logo.py [image.png]"""
import struct
import sys
from pathlib import Path

from PIL import Image

WIDTH, HEIGHT = 1024, 396  # a multiple of 4 each (RGBA8 is stored in 4 x 4 tiles); the picture keeps its proportions
root = Path(__file__).resolve().parent
source = Path(sys.argv[1]) if len(sys.argv) > 1 else root / "title_logo.png"
target = root.parent / "native/petari/src/Game/Screen/NebulaTitleLogo.inc"

image = Image.open(source).convert("RGBA")
# The almost invisible haze around the letters (alpha 1 to 40 of 255, a noise of faint white specks) is cleared, and the body
# (alpha 241 and over: 253 in the picture) made fully opaque.
channel = image.getchannel("A").point([0 if a <= 40 else 255 if a >= 241 else a for a in range(256)])
image.putalpha(channel)
image = image.crop(channel.getbbox())

# Fit inside the texture with a small margin, resizing with premultiplied colours so the edge does not go dark.
margin = 4
scale = min((WIDTH - 2 * margin) / image.width, (HEIGHT - 2 * margin) / image.height)
size = (max(1, round(image.width * scale)), max(1, round(image.height * scale)))
pixels = image.load()
for y in range(image.height):
    for x in range(image.width):
        r, g, b, a = pixels[x, y]
        pixels[x, y] = (r * a // 255, g * a // 255, b * a // 255, a)
small = image.resize(size, Image.LANCZOS)
padded = Image.new("RGBA", (WIDTH, HEIGHT), (0, 0, 0, 0))
padded.paste(small, ((WIDTH - size[0]) // 2, (HEIGHT - size[1]) // 2))

data = bytearray()
pixels = padded.load()
for ty in range(0, HEIGHT, 4):
    for tx in range(0, WIDTH, 4):
        ar, gb = bytearray(), bytearray()
        for y in range(4):
            for x in range(4):
                r, g, b, a = pixels[tx + x, ty + y]
                if a:
                    r, g, b = min(255, r * 255 // a), min(255, g * 255 // a), min(255, b * 255 // a)
                ar += bytes((a, r))
                gb += bytes((g, b))
        data += ar + gb
header = (bytes((6, 1)) + struct.pack(">HH", WIDTH, HEIGHT) + bytes((0, 0, 0, 0)) + struct.pack(">HI", 0, 0) +
          bytes((0, 0, 0, 0, 1, 1, 0, 0, 1, 0)) + struct.pack(">hI", 0, 0x20))
assert len(header) == 0x20
blob = header + bytes(data)
lines = [
    "// Generated by tools/gen_title_logo.py from tools/title_logo.png: do not edit.",
    "// A BTI file (header and image big-endian): RGBA8, %d x %d." % (WIDTH, HEIGHT),
    "alignas(32) static unsigned char cTitleLogoBti[%d] = {" % len(blob),
]
for i in range(0, len(blob), 40):
    lines.append(",".join(str(b) for b in blob[i:i + 40]) + ",")
lines.append("};")
target.write_text("\n".join(lines) + "\n")
print("wrote", target, len(blob), "bytes, file", target.stat().st_size)
